PROMPT = "Describe this image."

inputs = processor(
    images=test_image,
    text=PROMPT,
    return_tensors="pt",
)

# Move inputs to the GPU.
# Preserve integer types for token IDs.
inputs = {
    name: (
        tensor.to("cuda", dtype=torch.float16)
        if tensor.is_floating_point()
        else tensor.to("cuda")
    )
    for name, tensor in inputs.items()
}

with torch.inference_mode():
    generated_ids = model.generate(
        **inputs,
        num_beams=4,
        max_new_tokens=64,
        do_sample=False,
    )

caption = processor.batch_decode(
    generated_ids,
    skip_special_tokens=True,
)[0].strip()

print("\nBLIP-2 caption:", caption)

# Select a repeatable pilot sample: 3 images per category.
