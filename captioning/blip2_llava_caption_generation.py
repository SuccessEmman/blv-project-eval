PROMPT = "Describe this image."

GENERATION_SETTINGS = {
    "num_beams": 4,
    "max_new_tokens": 64,
    "do_sample": False,
}

CAPTION_OUTPUT_FOLDER = OUTPUT_FOLDER / "generated_captions"
CAPTION_OUTPUT_FOLDER.mkdir(exist_ok=True)

RESULTS_FILE = CAPTION_OUTPUT_FOLDER / "blip2_final_results.csv"
CONFIG_FILE = CAPTION_OUTPUT_FOLDER / "blip2_final_config.json"
ERROR_FILE = CAPTION_OUTPUT_FOLDER / "blip2_final_errors.csv"

# Record the configuration used for this run.
run_config = {
    "model": "Salesforce/blip2-flan-t5-xl",
    "revision": getattr(model.config, "_commit_hash", None),
    "prompt": PROMPT,
    "generation_settings": GENERATION_SETTINGS,
    "loading": "8-bit",
    "seed": 2026,
    "packages": {
        name: version(name)
        for name in ["torch", "transformers", "accelerate", "bitsandbytes"]
    },
    "sample_filenames": sorted(sample_manifest["file_name"].tolist()),
}

# Resume only when the configuration and selected sample match.
if CONFIG_FILE.exists():
    with open(CONFIG_FILE, "r") as file:
        saved_config = json.load(file)

    assert saved_config == run_config, (
        "Configuration differs from the saved run. "
        "Use separate output filenames for a different experiment."
    )
else:
    assert not RESULTS_FILE.exists(), (
        "Results exist without a configuration file. Check them before continuing."
    )

    with open(CONFIG_FILE, "w") as file:
        json.dump(run_config, file, indent=2)

if RESULTS_FILE.exists():
    existing = pd.read_csv(RESULTS_FILE, keep_default_na=False)
    assert existing["file_name"].is_unique, "Duplicate saved results found."

    # Retry any previously saved empty responses.
    existing = existing[existing["caption"].str.strip().ne("")]
    results = existing.to_dict("records")
else:
    results = []

completed = {record["file_name"] for record in results}

errors = (
    pd.read_csv(ERROR_FILE, keep_default_na=False).to_dict("records")
    if ERROR_FILE.exists()
    else []
)

print("Already completed:", len(completed))

model.eval()

for row in sample_manifest.itertuples(index=False):
    if row.file_name in completed:
        continue

    try:
        with Image.open(row.image_path) as source:
            image = source.convert("RGB")

        inputs = processor(
            images=image,
            text=PROMPT,
            return_tensors="pt",
        )

        inputs = {
            name: (
                tensor.to("cuda", dtype=torch.float16)
                if tensor.is_floating_point()
                else tensor.to("cuda")
            )
            for name, tensor in inputs.items()
        }

        with torch.inference_mode():
            generated_ids = model.generate(
                **inputs,
                **GENERATION_SETTINGS,
            )

        caption = processor.batch_decode(
            generated_ids,
            skip_special_tokens=True,
        )[0].strip()

        if not caption:
            raise ValueError("Model returned an empty caption.")

    except Exception as error:
        errors.append({
            "file_name": row.file_name,
            "error": str(error),
        })

        pd.DataFrame(errors).to_csv(ERROR_FILE, index=False)
        print(f"FAILED: {row.file_name} — {error}")

        # Stop on GPU memory errors rather than repeating the failure.
        if isinstance(error, torch.cuda.OutOfMemoryError):
            raise

        continue

    results.append({
        "image_id": row.image_id,
        "file_name": row.file_name,
        "split": row.split,
        "stratum": row.stratum,
        "model": run_config["model"],
        "prompt": PROMPT,
        "caption": caption,
    })

    # Save after each successful image.
    pd.DataFrame(results).to_csv(RESULTS_FILE, index=False)
    completed.add(row.file_name)

    print(f"{len(completed)}/250 completed: {row.file_name}")

print("\nResults saved to:", RESULTS_FILE)