"""**Load BLIP-2**"""

import torch
from importlib.metadata import version
from transformers import (
    Blip2Processor,
    Blip2ForConditionalGeneration,
    BitsAndBytesConfig,
    set_seed,
)

assert torch.cuda.is_available(), "A GPU runtime is required."

set_seed(2026)

MODEL_ID = "Salesforce/blip2-flan-t5-xl"

# Reduce memory use by loading eligible model layers in 8-bit.
quantization_config = BitsAndBytesConfig(load_in_8bit=True)

# Prepares images and text for this model.
processor = Blip2Processor.from_pretrained(MODEL_ID)

# Loads the pretrained model onto the GPU.
model = Blip2ForConditionalGeneration.from_pretrained(
    MODEL_ID,
    quantization_config=quantization_config,
    device_map={"": 0},
    torch_dtype=torch.float16,
)

model.eval()

print("BLIP-2 loaded successfully.")
print("Model:", MODEL_ID)
print("Loading: 8-bit")
print("Model revision:", getattr(model.config, "_commit_hash", None))

for package in ["torch", "transformers", "accelerate", "bitsandbytes"]:
    print(f"{package}: {version(package)}")

