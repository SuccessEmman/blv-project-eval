for row in sample_manifest.itertuples(index=False):
    if row.file_name in completed:
        continue

    try:
        with Image.open(row.image_path) as source:
            image = source.convert("RGB")

        inputs = processor(
            images=image,
            text=formatted_prompt,
            return_tensors="pt",
        )

        inputs = {
            name: (
                tensor.to("cuda", dtype=torch.float16)
                if tensor.is_floating_point()
                else tensor.to("cuda")
            )
            for name, tensor in inputs.items()
        }

        with torch.inference_mode():
            generated_ids = model.generate(
                **inputs,
                **GENERATION_SETTINGS,
            )

        # Remove input tokens so only the answer is saved.
        input_length = inputs["input_ids"].shape[1]
        answer_ids = generated_ids[:, input_length:]

        caption = processor.batch_decode(
            answer_ids,
            skip_special_tokens=True,
        )[0].strip()

        if not caption:
            raise ValueError("Model returned an empty caption.")

    except Exception as error:
        errors.append({
            "file_name": row.file_name,
            "error": str(error),
        })

        pd.DataFrame(errors).to_csv(ERROR_FILE, index=False)
        print(f"FAILED: {row.file_name} — {error}")

        if isinstance(error, torch.cuda.OutOfMemoryError):
            raise

        continue

    results.append({
        "image_id": row.image_id,
        "file_name": row.file_name,
        "split": row.split,
        "stratum": row.stratum,
        "model": MODEL_ID,
        "prompt": PROMPT,
        "caption": caption,
    })

    # Save after each successful image.
    pd.DataFrame(results).to_csv(RESULTS_FILE, index=False)
    completed.add(row.file_name)

    print(f"{len(completed)}/250 completed: {row.file_name}")

print(f"\nSuccessfully saved captions: {len(results)}/250")

